    @classmethod
    def resolve_alias(cls, city: str) -> str:
        """Return the canonical English city name, or the input unchanged."""
        return cls.CITY_ALIASES.get(city.lower(), city)

    @classmethod
    def resolve_country(cls, location: str | None) -> str | None:
        if not location:
            return None

        normalized = location.strip().lower()

        return cls.resolve_region(normalized) or cls.resolve_city_country(normalized)

    @classmethod
    def resolve_city_country(cls, location: str | None) -> str | None:
        """
        Country for a city/location, matched on the whole string or any single
        token. Regions are not matched here (see resolve_region).
        """
        if not location:
            return None

        normalized = location.strip().lower()

        # 1. Exact match
        if normalized in cls.CITY_TO_COUNTRY:
            return cls.CITY_TO_COUNTRY[normalized]

        # 2. Token-based fallback: cities and country names only, never regions.
        for part in normalized.split():
            cleaned = _TOKEN_JUNK.sub("", part).strip("-'")
            if not cleaned:
                continue

            country = cls.CITY_TO_COUNTRY.get(cleaned) or cls._country_names().get(
                cleaned
            )
            if country:
                return country

        return None

    @classmethod
    def resolve_region(cls, location: str | None) -> str | None:
        """
        Country for a country name, localised country name or region
        ("Österreich", "Bayern", "Zuid-Holland"), else None. Whole-string match.
        """
        if not location:
            return None
        normalized = location.strip().lower()
        return cls.REGION_TO_COUNTRY.get(normalized) or cls._country_names().get(
            normalized
        )

    @classmethod
    @cache
    def _country_names(cls) -> dict[str, str]:
        names = {*cls.CITY_TO_COUNTRY.values(), *cls.REGION_TO_COUNTRY.values()}
        return {name.lower(): name for name in names}

    @classmethod
    def is_country(cls, location: str | None) -> bool:
        if not location:
            return False

        normalized = location.strip().lower()
        if not normalized:
            return False

        countries = {country.lower() for country in cls.CITY_TO_COUNTRY.values()}
        return normalized in countries
